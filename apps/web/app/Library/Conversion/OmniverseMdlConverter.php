<?php

namespace App\Library\Conversion;

use App\Library\FileStore;
use App\Models\File;
use App\Models\QualityTier;
use App\Models\Representation;
use App\Models\Target;

/**
 * Writes an OmniPBR MDL module that references the canonical texture set.
 * The textures travel with the representation under their canonical roles;
 * the module names them by file name so a namespace projection can place
 * them next to the .mdl.
 */
class OmniverseMdlConverter implements Converter
{
    public const VERSION = '1.0.0';

    public function __construct(private readonly FileStore $files) {}

    public function supports(Target $target): bool
    {
        return $target->slug === 'omniverse';
    }

    public function tool(): string
    {
        return 'opal omniverse mdl converter';
    }

    public function version(): string
    {
        return self::VERSION;
    }

    /**
     * @return array<string, File>
     */
    public function convert(Representation $canonical, Target $target, QualityTier $quality): array
    {
        $textures = $canonical->filesByRole();
        $variant = $canonical->variant;
        $module = preg_replace('/[^A-Za-z0-9_]/', '_', $variant->code) ?? 'material';

        $mdl = $this->render($module, $variant->code, $variant->name, $textures, (float) ($variant->effectiveTileWidthMm() ?? 1000), (float) ($variant->effectiveTileHeightMm() ?? 1000));

        $file = $this->files->store($mdl, $variant->code.'.mdl', 'text/x-mdl');

        return ['mdl' => $file, ...$textures];
    }

    /**
     * @param  array<string, File>  $textures
     */
    private function render(string $module, string $code, string $name, array $textures, float $widthMm, float $heightMm): string
    {
        $texture = fn (string $role): ?string => isset($textures[$role]) ? basename($textures[$role]->object_key) : null;

        $lines = [
            'mdl 1.7;',
            '',
            'import ::OmniPBR::OmniPBR;',
            'import ::anno::*;',
            'import ::tex::*;',
            '',
            "// OPAL {$code} — {$name}",
            '// Generated by opal omniverse mdl converter '.self::VERSION,
            "// Real-world size: {$widthMm} mm × {$heightMm} mm",
            '',
            "export material {$module}(*)",
            '[[',
            "    anno::display_name(\"{$name} [{$code}]\"),",
            '    anno::author("OPAL"),',
            "    anno::key_words(string[](\"opal\", \"{$code}\"))",
            ']]',
            ' = ::OmniPBR::OmniPBR(',
        ];

        $params = [];

        if (($base = $texture('base_color')) !== null) {
            $params[] = "    diffuse_texture: texture_2d(\"./{$base}\", ::tex::gamma_srgb)";
        }

        if (($roughness = $texture('roughness')) !== null) {
            $params[] = "    reflectionroughness_texture: texture_2d(\"./{$roughness}\", ::tex::gamma_linear)";
        }

        if (($metallic = $texture('metallic')) !== null) {
            $params[] = "    metallic_texture: texture_2d(\"./{$metallic}\", ::tex::gamma_linear)";
        }

        if (($normal = $texture('normal')) !== null) {
            $params[] = "    normalmap_texture: texture_2d(\"./{$normal}\", ::tex::gamma_linear)";
        }

        if (($ao = $texture('ao')) !== null) {
            $params[] = "    ao_texture: texture_2d(\"./{$ao}\", ::tex::gamma_linear)";
        }

        if (($opacity = $texture('opacity')) !== null) {
            $params[] = "    opacity_texture: texture_2d(\"./{$opacity}\", ::tex::gamma_linear)";
        }

        $params[] = sprintf('    texture_scale: float2(%s, %s)', $this->number(1000 / max($widthMm, 1)), $this->number(1000 / max($heightMm, 1)));

        return implode("\n", [...$lines, implode(",\n", $params), ');', '']);
    }

    private function number(float $value): string
    {
        return rtrim(rtrim(number_format($value, 6, '.', ''), '0'), '.') ?: '0';
    }
}
